-- Q1. WE NEED TO MAKE AN INDEX OF THE BRANCH COLUMN AS IT USED VERY WIDELY TO FETCH DATA

CREATE INDEX idx_Branch -- NAME THE INDEX
ON Accounts(Branch); -- CREATE ON BASIS OF WHICH COLUMN

SHOW INDEX 
FROM Accounts; -- SHOWING INDEX

CREATE INDEX idx_2 
ON Accounts(Branch, Balance); -- COMPOSITE INDEX : MADE UDING MULTIPLE COLUMNS

SHOW INDEX 
FROM Accounts; -- SHOWING COMPOSITE INDEX

DROP INDEX idx_Branch ON Accounts; -- DROPPING INDEX
DROP INDEX idx_2 ON Accounts; -- DROPPING INDEX

-- STORED PROCEDURES : PREDEFINED SET OF STATEMENTS THAT WE CAN SAVE IN THE DATABASE AND EXECUTE WHENEVER NEEDED
				-- NOTE : IT IS JUST LIKE PYTHON FUNCTIONS
                
-- Q1. MAKE A PROCEDURE SO THAT WHENEVER WE ARE ASKED FOR AN ACCOUNT ID WE SHOW THE BALANCE

-- CHANGING DELIMITER VALUE
DELIMITER $$ 

CREATE PROCEDURE Check_Balance(IN Acc_ID INT) -- NAME THE PROCEDURE, NAME THE PARAMTER WITH DATA TYPE WE WILL USE, PREFERABLY USE AN ALIAS 
BEGIN
	SELECT Balance
    FROM Accounts
    WHERE Account_ID = Acc_ID;
END $$ -- WE CHANGE DELIMITER VALUE TO $$ SO THAT SQL DOESNT GET CONFUSED WHEN WE USE ';' INSIDE THE PROCEDURE COMMANDS

-- RESETING DELIMITER VALUE
DELIMITER ; 

CALL Check_Balance(1); -- NOW WE CALL THE PROCEDURE JUST LIKE PYTHON WITH AN INPUT VALUE FOR THE PROCEDURE TO PERFORM THE QUERIES
CALL Check_Balance(2); -- 300 

DROP PROCEDURE IF EXISTS check_Balance; -- DROPPING THE PROCEDURE