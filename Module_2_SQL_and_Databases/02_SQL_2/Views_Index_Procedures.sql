-- VIEWS : A VIRTUAL TABLE BASED ON THE RESULT OF AN SQL QUERY, USED TO MAINTAIN PRIVACY

USE Inventory;

SELECT * FROM Orders;
SELECT * FROM Customers;

-- Q1. THE SALES TEAM JUST WANTS THE NAME AND CUSTOMER ID FROM THE CUSTOMER TABLE, SO WE GIVE THEM A VIEW OF IT AND NOT ORIGINAL DATA

CREATE VIEW View1 AS -- MAKE THE VIEW
SELECT Customer_ID, Name FROM Customers; -- VIEW SHOULD HAVE THESE

SELECT * FROM View1; -- A VIEW WILL ACT JUST AS A TABLE SO WE CAN RUN CLAUSES ON IT ASWELL

-- Q2. THE SALES TEAM JUST WANTS THE DATA OF CUSTOMERS WHO HAVE AN ORDER, SO WE MAKE A JOIN AND THEN GIVE THEM A VIEW OF IT

CREATE VIEW View2 AS -- CREATE VIEW
SELECT c.Customer_ID, c.Name -- IN A VIEW WE NEED TO SPECIFY WHICH COLUMNS WE WANT
FROM Customers c
INNER JOIN Orders o
ON c.Customer_ID = o.Customer_ID; -- CREATING THE JOIN

SELECT * FROM View2;

DROP VIEW View1; -- HOW TO DROP A VIEW

-- INDEX : SPECIAL DATABASE OBJECTS THAT MAKE DATA RETRIEVAL FAST, GENERALLY USING PRIMARY KEYS
-- THESE INDEXES MAKE THE SELECT QUERIES FASTER WHEN WE HAVE MILLIONS OF ROWS
-- DRAWBACK : MAKES THE TABLE QUERIES LIKE UPDATE ALTER DELETE ETC SLOW

USE Company;

CREATE TABLE Accounts(
	Account_ID INT PRIMARY KEY,
    Name VARCHAR(30),
    Balance DECIMAL(10,2),
    Branch VARCHAR(50)
);

